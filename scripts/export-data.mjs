#!/usr/bin/env node
// Exports a snapshot of the COLDEX sample data into data/coldex-data.js, which the
// website loads instead of querying Supabase live.
//
// Run from the project folder:   node scripts/export-data.mjs
//
// It reads ONLY through the same public database functions the website used to call,
// with the same public (anon) key, so the snapshot can never contain anything the
// site wasn't already showing. The `requests` table and the staging/temp tables are
// never touched.
//
// Run it again, then commit and push data/coldex-data.js, after each database update.

import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SUPABASE_URL = 'https://qkmxlmpotcsfxroxbnir.supabase.co';
const SUPABASE_ANON_KEY = 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6InFrbXhsbXBvdGNzZnhyb3hibmlyIiwicm9sZSI6ImFub24iLCJpYXQiOjE3NTg2NjUwMjUsImV4cCI6MjA3NDI0MTAyNX0.v3_MMFUjsGZUd5qgUX0k31xCz0Syi9syEnY_C-QZouU';

const OUT_FILE = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'data', 'coldex-data.js');
const ROW_CAP = 1000;       // Supabase silently truncates function results at this many rows
const CONCURRENCY = 8;

async function rpc(name, args = {}, attempt = 1) {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/rpc/${name}`, {
    method: 'POST',
    headers: {
      apikey: SUPABASE_ANON_KEY,
      Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(args),
  });
  if (!res.ok) {
    if (attempt < 3) {                       // brief retry for timeouts / hiccups
      await new Promise(r => setTimeout(r, 1000 * attempt));
      return rpc(name, args, attempt + 1);
    }
    throw new Error(`${name}(${JSON.stringify(args)}) failed: ${res.status} ${await res.text()}`);
  }
  return res.json();
}

// Run async tasks with a small concurrency limit, keeping input order.
async function mapLimit(items, limit, fn) {
  const out = new Array(items.length);
  let next = 0;
  await Promise.all(Array.from({ length: limit }, async () => {
    while (next < items.length) {
      const i = next++;
      out[i] = await fn(items[i], i);
    }
  }));
  return out;
}

const byText = (a, b) => (a ?? '').toString().localeCompare((b ?? '').toString(), 'en', { numeric: true });

console.log('Reading core list…');
const cores = (await rpc('get_allan_hills_cores')).sort((a, b) => byText(a.core_code, b.core_code));
const coreIds = (await rpc('coldex_get_core_ids')).map(r => r.core_id).sort(byText);
console.log(`  ${cores.length} cores in the Allan Hills table, ${coreIds.length} cores with samples`);

console.log('Reading sample records…');
const samples = [];
for (const core of coreIds) {
  const rows = await rpc('search_samples', { p_core_id: core, p_min_depth: null, p_max_depth: null, p_status: null });
  if (rows.length >= ROW_CAP) throw new Error(`${core} returned ${rows.length} records — likely cut off at the ${ROW_CAP}-row limit`);
  samples.push(...rows);
}
samples.sort((a, b) => byText(a.core_id, b.core_id) || (a.top_depth_m - b.top_depth_m) || byText(a.record_id, b.record_id));
console.log(`  ${samples.length} sample records`);

console.log('Reading subsamples…');
const withSubs = samples.filter(s => s.has_subsamples);
let done = 0;
const detail = await mapLimit(withSubs, CONCURRENCY, async (s) => {
  const rows = await rpc('get_sample_detail', { p_record_id: s.record_id });
  if (++done % 100 === 0) process.stdout.write(`  ${done}/${withSubs.length}\r`);
  return { s, subs: rows[0]?.subsamples ?? [] };
});
const subsamples = [];
for (const { s, subs } of detail) {
  if (subs.length !== (s.subsample_count ?? 0)) {
    console.warn(`  warning: ${s.record_id} lists ${s.subsample_count} subsamples but ${subs.length} came back`);
  }
  for (const sub of subs) subsamples.push({ record_id: s.record_id, core_id: s.core_id, ...sub });
}
subsamples.sort((a, b) => byText(a.core_id, b.core_id) || byText(a.record_id, b.record_id) || byText(a.subsample_id, b.subsample_id));
console.log(`  ${subsamples.length} subsamples                    `);

// One record per line so changes show up as readable diffs in git.
const lines = (rows) => '[\n' + rows.map(r => '  ' + JSON.stringify(r)).join(',\n') + '\n]';
const generated = new Date().toISOString();
const js =
`// Snapshot of the COLDEX sample database. Generated by scripts/export-data.mjs — do not edit by hand.
window.COLDEX_DATA = {
  generated: ${JSON.stringify(generated)},
  cores: ${lines(cores)},
  samples: ${lines(samples)},
  subsamples: ${lines(subsamples)}
};
`;
await mkdir(dirname(OUT_FILE), { recursive: true });
await writeFile(OUT_FILE, js);
console.log(`\nWrote ${OUT_FILE}  (${(js.length / 1024 / 1024).toFixed(2)} MB)`);
console.log(`Snapshot time: ${generated}`);
